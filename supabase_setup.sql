-- كنافة البشوات: سياسات آمنة للقراءة العامة وإدارة المنتجات للمديرين.
-- راجع README_AR.md ونفّذ هذا الملف من Supabase SQL Editor بعد التأكد من اسم المشروع.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price numeric(10,2) not null check (price >= 0),
  image_url text,
  category text not null
);

alter table public.products enable row level security;

-- جدول ربط حسابات Supabase Auth المصرّح لها بإدارة المتجر.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;

-- صلاحيات SQL الأساسية؛ سياسات RLS أدناه هي التي تحدد الصفوف المسموح بها.
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant select on public.admin_users to authenticated;

-- المدير يستطيع فقط قراءة سجلّه؛ لا توجد سياسة تسمح للمستخدم بترقية نفسه إلى مدير.
drop policy if exists "Admins can read own admin record" on public.admin_users;
create policy "Admins can read own admin record" on public.admin_users
for select to authenticated using (user_id = (select auth.uid()));

-- المنتجات مرئية للزوار، أما التغيير فمسموح للمديرين فقط.
drop policy if exists "Anyone can view products" on public.products;
create policy "Anyone can view products" on public.products
for select to anon, authenticated using (true);
drop policy if exists "Admins can insert products" on public.products;
create policy "Admins can insert products" on public.products
for insert to authenticated with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));
drop policy if exists "Admins can update products" on public.products;
create policy "Admins can update products" on public.products
for update to authenticated using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));
drop policy if exists "Admins can delete products" on public.products;
create policy "Admins can delete products" on public.products
for delete to authenticated using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

-- حاوية صور عامة لعرض صور المنتجات في المتجر.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 5242880, array['image/png','image/jpeg','image/webp','image/gif'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/png','image/jpeg','image/webp','image/gif'];

drop policy if exists "Admins can upload product images" on storage.objects;
create policy "Admins can upload product images" on storage.objects
for insert to authenticated with check (bucket_id = 'product-images' and exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));
drop policy if exists "Admins can update product images" on storage.objects;
create policy "Admins can update product images" on storage.objects
for update to authenticated using (bucket_id = 'product-images' and exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
with check (bucket_id = 'product-images' and exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));
drop policy if exists "Admins can delete product images" on storage.objects;
create policy "Admins can delete product images" on storage.objects
for delete to authenticated using (bucket_id = 'product-images' and exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

